"""Write results/recommender/: Pareto fronts per workload, a check of the memory model against
the measured runs, example scenarios, and a quality-vs-memory chart with the fronts drawn in."""
import csv
from pathlib import Path

import numpy as np

from recommender import profiles as P
from recommender.engine import Request, recommend

# Typical deployments on the A10G (24 GB) used for every run: the 7B model in bf16 takes
# ~15 GB, leaving about 7 GiB for KV caches and activations.
FREE = 7.0
SCENARIOS = [
    ("One user, no speed limit", dict(batch=1, free_gpu_gib=FREE, min_quality=95)),
    ("Interactive: at most 30% slower", dict(batch=1, free_gpu_gib=FREE, min_quality=95, max_slowdown=1.3)),
    ("Same, quality guaranteed (95% lower bound)", dict(batch=1, free_gpu_gib=FREE, min_quality=95, max_slowdown=1.3, strict=True)),
    ("Busy server: 32 requests at once, ≤30% slower", dict(batch=32, free_gpu_gib=FREE, min_quality=90, max_slowdown=1.3)),
    ("Quality can drop to 75%, ≤10% slower", dict(batch=1, free_gpu_gib=FREE, min_quality=75, max_slowdown=1.1)),
]


def measured_vs_predicted(profiles, models, results_dir):
    """Mean GPU KV bytes measured per (workload, method) vs what the memory model predicts."""
    rows = []
    for wl in profiles:
        runs = P._runs(Path(results_dir) / "json", wl)
        for m, rs in runs.items():
            vals = [(r["input_tokens"], r["output_tokens"], r.get("kv_cache_gpu_bytes") or r.get("kv_cache_bytes"))
                    for r in rs.values() if r.get("kv_cache_bytes")]
            if not vals:
                continue
            meas = np.mean([v[2] for v in vals])
            pred = np.mean([P.gpu_kv_bytes(m, v[0], v[1], models) for v in vals])
            rows.append({"workload": wl, "method": m, "measured_mib": round(meas / 2**20, 1),
                         "predicted_mib": round(pred / 2**20, 1), "error_pct": round(100 * (pred - meas) / meas, 1)})
    return rows


def write_report(profiles, models, results_dir="results"):
    out = Path(results_dir) / "recommender"
    out.mkdir(parents=True, exist_ok=True)
    md = ["# Quality-aware recommender: Pareto fronts and example choices", "",
          "Generated by `python main.py recommend --report` from the runs in `results/json/` "
          "(Qwen2.5-Coder-7B-Instruct, A10G 24 GB). Quality retention = method ÷ full cache × 100 on the same "
          "samples; *low* = 95 % lower confidence bound from a paired bootstrap. GPU KV = KV-cache bytes left "
          "on the GPU per request. Slowdown = time per generated token ÷ the full cache's.", ""]

    md += ["## Pareto front per workload (at the measured prompt length)", "",
           "A method is on the front when no other method is at the same time smaller on the GPU, at least as "
           "good in quality and at least as fast. Everything off the front is never the best choice.", ""]
    fronts = {}
    for wl in profiles:
        res = recommend(Request(wl), profiles, models)
        fronts[wl] = res
        md += [f"### {wl}: {P.WORKLOADS[wl][2]}, prompt ≈ {res['prompt_tokens']} tokens", "",
               "| method | quality kept | low | GPU KV / request | KV saved | slowdown | on front |",
               "|:--|--:|--:|--:|--:|--:|:-:|"]
        for c in sorted(res["candidates"], key=lambda c: c.gpu_kv_gib):
            md.append(f"| {c.method} | {c.retention_measured:.0f}% | {c.retention_lo:.0f}% | {c.gpu_kv_gib * 1024:.0f} MiB | "
                      f"{c.kv_reduction_pct:.0f}% | {c.slowdown:.2f}x | {'●' if c.pareto else ''} |")
        md.append("")

    md += ["## What the recommender picks", "",
           f"Every scenario assumes {FREE:g} GiB of GPU memory free for KV caches (A10G after loading the 7B model).", "",
           "| scenario | " + " | ".join(profiles) + " |", "|:--|" + ":--|" * len(profiles)]
    csv_rows = []
    for name, kw in SCENARIOS:
        cells = []
        for wl in profiles:
            res = recommend(Request(wl, **kw), profiles, models)
            ch = res["choice"]
            cells.append("none fits" if ch is None else
                         f"**{ch.method}** ({ch.kv_reduction_pct:.0f}% less KV, {ch.slowdown:.2f}x)")
            csv_rows.append({"scenario": name, "workload": wl, **{k: v for k, v in kw.items()},
                             "choice": ch.method if ch else "", "kv_saved_pct": ch.kv_reduction_pct if ch else "",
                             "quality_retention_pct": ch.retention_measured if ch else "",
                             "slowdown_x": ch.slowdown if ch else ""})
        md.append(f"| {name} | " + " | ".join(cells) + " |")
    md += ["", "Why these answers:", "",
           "- With no speed limit, CPU offloading always wins: it keeps the exact answers and leaves only one layer "
           "of the cache on the GPU, but each token is up to 2x slower on long prompts.",
           "- With a speed limit, KIVI is the safe choice for long-code understanding; SnapKV wins on the position "
           "test, where the question tells it which code to keep. StreamingLLM is never chosen at 95 %, because it "
           "drops the middle of the context.",
           "- On short prompts (custom) the eviction methods change nothing, because the prompt fits in the budget.",
           "- *Quality guaranteed* uses the 95 % lower confidence bound instead of the average, so a method only "
           "passes if the samples show it reliably keeps 95 %. On LongCodeU this moves the choice from 2-bit to "
           "4-bit KIVI, because 2-bit KIVI's bound is below 95 % even though its average is 96 %.", ""]

    check = measured_vs_predicted(profiles, models, results_dir)
    md += ["## Check: memory model vs measured", "",
           "The recommender predicts GPU KV bytes for any prompt length from a formula per method "
           "(`recommender/profiles.py`). Here the formula is applied to each measured sample and compared "
           "with what was measured.", "",
           f"Bytes per cached token (measured): {models.bytes_per_token:,.0f}; layers: {models.layers}.", "",
           "| workload | method | measured MiB | predicted MiB | error |", "|:--|:--|--:|--:|--:|"]
    md += [f"| {r['workload']} | {r['method']} | {r['measured_mib']} | {r['predicted_mib']} | {r['error_pct']:+.1f}% |"
           for r in check]
    md += ["", "Limits: three workloads and one model, at most ~8K tokens. Beyond the measured prompt lengths the "
           "quality of KIVI/SnapKV/StreamingLLM is extrapolated and the output marks it with ⚠. Rerun the "
           "benchmarks at 16K/32K and the recommender picks them up automatically.", ""]

    chart = _chart(fronts, out / "pareto_fronts.png")
    if chart:
        md += ["![](pareto_fronts.png)", ""]
    (out / "recommender_report.md").write_text("\n".join(md))
    with open(out / "scenarios.csv", "w", newline="") as f:
        keys = sorted({k for r in csv_rows for k in r}, key=lambda k: list(csv_rows[0]).index(k) if k in csv_rows[0] else 99)
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(csv_rows)
    with open(out / "memory_model_check.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(check[0]))
        w.writeheader()
        w.writerows(check)
    print(f"wrote {out}/recommender_report.md, scenarios.csv, memory_model_check.csv" + (", pareto_fronts.png" if chart else ""))


def _chart(fronts, path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.ticker  # noqa: F401
    except ImportError:
        return None
    from compare_methods import method_style
    fig, axes = plt.subplots(1, len(fronts), figsize=(5 * len(fronts), 4.2), squeeze=False)
    for ax, (wl, res) in zip(axes[0], fronts.items()):
        cs = res["candidates"]
        for c in cs:
            col, mk = method_style(c.method)
            ax.scatter(c.gpu_kv_gib * 1024, c.retention_measured, color=col, marker=mk, s=60,
                       edgecolor="black" if c.pareto else "none", zorder=3, label=c.method)
            ax.plot([c.gpu_kv_gib * 1024] * 2, [c.retention_lo, c.retention_measured], color=col, lw=1, alpha=0.5)
            ax.annotate(f"{c.slowdown:.2f}x", (c.gpu_kv_gib * 1024, c.retention_measured), fontsize=7,
                        xytext=(5, 3), textcoords="offset points", color="#52514e")
        ax.set_xscale("log")
        ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g}"))
        ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
        ax.set_ylim(min(c.retention_lo for c in cs) - 5, max(c.retention_measured for c in cs) + 6)
        ax.set_title(f"{wl} (~{res['prompt_tokens']} tokens)")
        ax.set_xlabel("KV cache on GPU per request (MiB, log)")
        ax.set_ylabel("quality kept (% of full cache)")
        ax.grid(alpha=0.3)
    handles, labels = axes[0][0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=len(labels), frameon=False, fontsize=8)
    fig.suptitle("Quality vs KV cache left on the GPU. Outlined = Pareto front (memory, quality, speed); "
                 "label = slowdown per token; thin line down to the 95% lower bound", fontsize=10)
    fig.tight_layout(rect=(0, 0.07, 1, 0.95))
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path

#!/usr/bin/env bash
# Inspect first, then install only what is missing. Safe to re-run.
#   bash setup_env.sh            # uses the current python (SageMaker Distribution's conda env)
#   PY=python3.11 bash setup_env.sh
# Does NOT upgrade a working CUDA PyTorch, does NOT install FlashAttention / vLLM,
# and creates no AWS resources.
set -euo pipefail
cd "$(dirname "$0")"
PY="${PY:-python}"

echo "== inspection =="
command -v nvidia-smi >/dev/null && nvidia-smi --query-gpu=name,driver_version,memory.total,memory.free --format=csv \
  || echo "nvidia-smi not found (no GPU?)"
$PY --version
$PY -m pip show torch transformers accelerate 2>/dev/null | grep -E "^(Name|Version)" || true
df -h . | tail -1

TORCH_STATE=$($PY - <<'PYEOF'
try:
    import torch
    print("cuda" if torch.cuda.is_available() else "cpu-only")
except ImportError:
    print("missing")
PYEOF
)
echo "torch: $TORCH_STATE"
if [ "$TORCH_STATE" = "missing" ]; then
  echo "== installing torch (CUDA 12.4 wheels) =="
  $PY -m pip install torch --index-url https://download.pytorch.org/whl/cu124
elif [ "$TORCH_STATE" = "cpu-only" ] && command -v nvidia-smi >/dev/null; then
  echo "!! torch is installed without CUDA support although a GPU is present."
  echo "   Not changing it automatically. To fix: $PY -m pip install --force-reinstall torch --index-url https://download.pytorch.org/whl/cu124"
fi

echo "== installing missing Python packages =="
$PY -m pip install -q -r requirements.txt

if [ "${WITH_BNB:-0}" = "1" ]; then
  echo "== bitsandbytes (4-bit weights) =="
  $PY -m pip install -q bitsandbytes
fi

echo "== lock file =="
{
  echo "# Generated by setup_env.sh on $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "# python $($PY -c 'import platform;print(platform.python_version())')"
  $PY - <<'PYEOF'
import torch
print(f"# torch {torch.__version__} cuda_runtime {torch.version.cuda} cuda_available {torch.cuda.is_available()}")
if torch.cuda.is_available():
    print(f"# gpu {torch.cuda.get_device_name(0)}")
PYEOF
  $PY -m pip freeze
} > requirements-lock.txt
echo "wrote requirements-lock.txt ($(wc -l < requirements-lock.txt) lines)"

$PY - <<'PYEOF'
import torch, transformers, accelerate
print("torch", torch.__version__, "| transformers", transformers.__version__, "| accelerate", accelerate.__version__)
print("CUDA available:", torch.cuda.is_available())
PYEOF
echo "== done. Next: export HF_TOKEN=...  then  python main.py report =="
